-- NYSBOE filer registry -- the join target for nysboe_contributions.filer_id.
--
-- data/nysboe/README.md noted that filer names live in a separate table and had
-- to be joined on filer_id. This is that table. Coverage is complete: all 13,707
-- distinct filer_ids in nysboe_contributions resolve here (100%), out of 64,795
-- filer ids in the registry.
--
-- filer_id is NOT unique -- 81,483 rows over 64,795 distinct ids, because a filer
-- recurs per candidate / election year. So the key is a surrogate and filer_id
-- gets a plain index. Join carefully: an unqualified join to this table fans out.
-- Use the dedicated committee view, or qualify by election_year.
--
-- Two quirks in the source export, both handled by
-- scripts/repair_listoffilers.py rather than silently:
--   1. Every data row carries one extra trailing empty field beyond the 20-column
--      header, hence trailing_blank below.
--   2. One row (filer 16993, 'Committee To Elect Mary Eileen "Mel" Callan, R.N.')
--      has inner quotes that are not doubled per RFC 4180, which shifts every
--      later field right by one and makes COPY fail outright.
--
-- district / candidate_district stay text: 13% and 9% of filled values are
-- non-numeric.
--
-- Source: NYSBOE ListOfFilers.csv. See data/nysboe/README.md.

DROP TABLE IF EXISTS nysboe_filers;

CREATE TABLE nysboe_filers (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    filer_type                  text,       -- State / County / Federal
    compliance_type             text,
    committee_type              text,
    filer_id                    bigint NOT NULL,
    name                        text NOT NULL,
    office                      text,
    district                    text,
    county                      text,
    municipality                text,
    address                     text,       -- single unparsed line
    registration_date           date,
    termination_date            date,
    status                      text,       -- ACTIVE / TERMINATED / ...
    candidate_name              text,
    election_year               integer,
    candidate_office            text,
    candidate_district          text,
    purpose_type                text,
    candidate_registration_date date,
    candidate_termination_date  date,

    trailing_blank              text        -- the export's stray 21st field
);

COMMENT ON TABLE nysboe_filers IS
    'NYSBOE filer registry; join target for nysboe_contributions.filer_id. filer_id is NOT unique (81,483 rows / 64,795 ids) because rows repeat per candidate and election year -- an unqualified join fans out.';

COMMENT ON COLUMN nysboe_filers.trailing_blank IS
    'Always NULL. The source CSV emits a 21st field on every data row that the 20-column header does not name; kept so the load is a faithful mirror.';
