-- NYC Campaign Finance Board bulk exports, as filed.
--
-- These are STAGING tables: one table per export file, one column per export
-- column, in file order, with no normalization. The repo's normalized schema
-- (contributions / contributors / recipients / employers / locations /
-- elections / filings / intermediaries) is populated FROM here, so a reload
-- never has to re-download or re-parse 419 MB of CSV.
--
-- WHY A SURROGATE KEY AND NOT REFNO: the repo's public.contributions carries
-- UNIQUE (refno), which this data cannot satisfy. REFNO is a filing PAGE
-- reference, not a transaction id -- it repeats across candidates and filings.
-- Measured over the 2,123,892-row export: only 204,266 distinct REFNOs, and
-- 'P0001-01' alone appears 4,490 times. Loading into a UNIQUE(refno) column
-- would silently discard ~90% of the file. Even
-- (election, recipid, filing, schedule, refno) still collides 2,549 times;
-- nothing short of the whole row is unique. So each staging row gets a
-- generated id, and the composite goes in a NON-unique index.
--
-- Columns the export always leaves empty are kept anyway, so the table is a
-- faithful mirror of the file: pageno, sequenceno, strno, strname, apartment
-- (and intstrno, intstrnm, intaptno on contributions) are blank in all rows.
--
-- Source: NYC CFB bulk download. See data/cfb/README.md.

DROP TABLE IF EXISTS cfb_contributions;
DROP TABLE IF EXISTS cfb_expenditures;
DROP TABLE IF EXISTS cfb_intermediaries;

-- ---------------------------------------------------------------- contributions
CREATE TABLE cfb_contributions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- election / recipient
    election        text NOT NULL,      -- '2021', '2025', suffix T/A/U
    officecd        text,               -- code, not a quantity ('IS' = indep. spending)
    recipid         text NOT NULL,
    canclass        text,               -- P / NP / UN
    recipname       text,
    committee       text,

    -- filing
    filing          integer,
    schedule        text,               -- ABC / M / D / X / N / G
    pageno          text,               -- always blank in this export
    sequenceno      text,               -- always blank in this export
    refno           text NOT NULL,      -- page reference; NOT unique

    -- transaction
    date            date,
    refunddate      date,
    amnt            numeric(14,2),
    matchamnt       numeric(14,2),
    prevamnt        numeric(14,2),
    pay_method      integer,

    -- contributor
    name            text,
    c_code          text,
    strno           text,               -- always blank
    strname         text,               -- always blank
    apartment       text,               -- always blank
    boroughcd       text,
    city            text,
    state           text,
    zip             text,
    occupation      text,
    empname         text,
    empstrno        text,
    empstrname      text,
    empcity         text,
    empstate        text,

    -- intermediary (bundler)
    intermno        integer,
    intermname      text,
    intstrno        text,               -- always blank
    intstrnm        text,               -- always blank
    intaptno        text,               -- always blank
    intcity         text,
    intst           text,
    intzip          text,
    intempname      text,
    intempstno      text,
    intempstnm      text,
    intempcity      text,
    intempst        text,
    intoccupa       text,
    int_c_code      text,

    -- flags, as filed
    purposecd       text,
    exemptcd        text,
    adjtypecd       integer,
    rr_ind          text,
    seg_ind         text
);

COMMENT ON TABLE cfb_contributions IS
    'NYC CFB contributions as filed. refno is a filing page reference and is NOT unique (204,266 distinct over 2,123,892 rows). pageno/sequenceno/strno/strname/apartment/int* street columns are blank in every row of this export.';

-- ---------------------------------------------------------------- expenditures
CREATE TABLE cfb_expenditures (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    election        text NOT NULL,
    officecd        text,
    candid          text NOT NULL,
    canclass        text,
    candlast        text,
    candfirst       text,
    candmi          text,
    committee       text,

    filing          integer,
    schedule        text,               -- F / D / N / L / X / H / Y
    pageno          text,               -- always blank
    sequenceno      text,               -- always blank
    refno           text NOT NULL,

    inv_date        date,
    date            date,

    name            text,               -- payee
    c_code          text,
    org_ind         text,
    strno           text,               -- always blank
    strname         text,               -- always blank
    apartment       text,               -- always blank
    city            text,
    state           text,
    zip             text,

    pay_method      text,               -- words here ('Unknown'), not the numeric code
    amnt            numeric(14,2),
    purposecd       text,
    purpose         text,
    explain         text,
    exemptcd        text,
    rr_ind          text,
    seg_ind         text
);

COMMENT ON TABLE cfb_expenditures IS
    'NYC CFB expenditures as filed. pay_method is free text here, unlike the numeric pay_method on cfb_contributions.';

-- ---------------------------------------------------------------- intermediaries
-- One row per (candidate, intermediary) with the bundled total. Every one of the
-- 131,905 INTERMNAME values in the contributions export appears here (verified
-- 100%), so this is the bundler registry for that file -- not an aggregate of it
-- (the amounts do not reconcile; it covers filings beyond the contributions export).
CREATE TABLE cfb_intermediaries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    election        text NOT NULL,
    officecd        text,
    candid          text NOT NULL,
    canclass        text,
    candlast        text,
    candfirst       text,
    candmi          text,
    committee       text,

    name            text NOT NULL,      -- the intermediary / bundler
    c_code          text,
    strno           text,               -- always blank
    strname         text,               -- always blank
    apartment       text,               -- always blank
    boroughcd       text,
    city            text,
    state           text,
    zip             text,
    occupation      text,
    empname         text,
    empstrno        text,
    empstrname      text,
    empcity         text,
    empstate        text,
    amnt            numeric(14,2)       -- total bundled
);

COMMENT ON TABLE cfb_intermediaries IS
    'NYC CFB intermediary (bundler) totals per candidate. 100% of INTERMNAME values in the contributions export resolve here, but amounts do NOT reconcile against it -- this covers filings the contributions export does not.';
